"""UPnP/DLNA (and OpenHome) renderer: upmpdcli in front of the player's MPD.

The group leader runs upmpdcli, named after the group like the AirPlay and
Spotify Connect receivers, so BubbleUPnP, mconnect, Linn Kazoo, foobar2000 or
a NAS app can cast to it (Tidal and Qobuz too, through BubbleUPnP or an
OpenHome controller). Members stop it, so a group appears once.

Now-playing details come from the renderer's own AVTransport service
(GetPositionInfo, the DIDL-Lite the controller sent), found once by SSDP.
"""

from __future__ import annotations

import asyncio
import logging
import re
import socket
import xml.etree.ElementTree as ET
from html import unescape
from typing import Any
from urllib.parse import urljoin, urlparse

import httpx

logger = logging.getLogger(__name__)

UNIT = "freesounder-upnp.service"
SSDP_ADDR = ("239.255.255.250", 1900)
RENDERER = "urn:schemas-upnp-org:device:MediaRenderer:1"
AVT = "urn:schemas-upnp-org:service:AVTransport:1"
_NS = {
    "didl": "urn:schemas-upnp-org:metadata-1-0/DIDL-Lite/",
    "dc": "http://purl.org/dc/elements/1.1/",
    "upnp": "urn:schemas-upnp-org:metadata-1-0/upnp/",
}


def _clean(value: str) -> str:
    return value.replace("\n", " ").replace("\r", " ").strip()


def render_conf(*, name: str, cache_dir: str, mpd_port: int = 6600) -> str:
    """upmpdcli.conf: one renderer (UPnP AV + OpenHome), no media server."""

    name = _clean(name) or "FreeSounder"
    return "\n".join(
        [
            "# Generated by freesounderd. Changes are overwritten.",
            f"friendlyname = {name}",
            f"ohproductroom = {name}",
            "upnpav = 1",
            "openhome = 1",
            "mpdhost = 127.0.0.1",
            f"mpdport = {mpd_port}",
            # upmpdcli owns MPD's queue while a controller plays.
            "ownqueue = 1",
            "checkcontentformat = 1",
            "ohmetapersist = 0",
            f"cachedir = {cache_dir}",
            "loglevel = 2",
            "",
        ]
    )


def _safe_xml(text: str) -> ET.Element | None:
    if "<!DOCTYPE" in text or "<!ENTITY" in text:
        return None
    try:
        return ET.fromstring(text)
    except ET.ParseError:
        return None


def parse_didl(didl: str) -> dict[str, Any]:
    """Title, artist, album and cover from a DIDL-Lite item."""

    root = _safe_xml(didl)
    if root is None:
        return {}
    item = root.find("didl:item", _NS)
    if item is None:
        return {}

    def text(path: str) -> str | None:
        node = item.find(path, _NS)
        return node.text.strip() if node is not None and node.text else None

    out: dict[str, Any] = {
        "title": text("dc:title"),
        "artist": text("upnp:artist") or text("dc:creator"),
        "album": text("upnp:album"),
        "image_url": text("upnp:albumArtURI"),
    }
    res = item.find("didl:res", _NS)
    if res is not None and res.get("duration"):
        out["duration"] = parse_hms(res.get("duration", ""))
    return {k: v for k, v in out.items() if v}


def parse_hms(value: str) -> float | None:
    m = re.match(r"^(\d+):(\d{1,2}):(\d{1,2}(?:\.\d+)?)$", value.strip())
    if not m:
        return None
    return int(m.group(1)) * 3600 + int(m.group(2)) * 60 + float(m.group(3))


def _ssdp_search(own_ip: str | None, wait: float = 2.0) -> list[str]:
    msg = (
        "M-SEARCH * HTTP/1.1\r\n"
        f"HOST: {SSDP_ADDR[0]}:{SSDP_ADDR[1]}\r\n"
        'MAN: "ssdp:discover"\r\nMX: 1\r\n'
        f"ST: {RENDERER}\r\n\r\n"
    ).encode()
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM, socket.IPPROTO_UDP)
    found: list[str] = []
    try:
        sock.settimeout(wait)
        sock.setsockopt(socket.IPPROTO_IP, socket.IP_MULTICAST_TTL, 1)
        sock.sendto(msg, SSDP_ADDR)
        while True:
            try:
                data, addr = sock.recvfrom(4096)
            except TimeoutError:
                break
            if own_ip and addr[0] != own_ip:
                continue
            for line in data.decode("utf-8", "replace").split("\r\n"):
                key, _, value = line.partition(":")
                if key.strip().lower() == "location":
                    found.append(value.strip())
    except OSError:
        logger.debug("SSDP search failed", exc_info=True)
    finally:
        sock.close()
    return found


class RendererInfo:
    """Reads the current track from our own upmpdcli (AVTransport)."""

    def __init__(self, http: httpx.AsyncClient, own_ip: Any) -> None:
        self.http = http
        self.own_ip = own_ip  # callable -> str
        self._control: str | None = None
        self._next_search = 0.0

    async def _find(self) -> str | None:
        loop = asyncio.get_running_loop()
        if loop.time() < self._next_search:
            return None
        self._next_search = loop.time() + 30
        for location in await asyncio.to_thread(_ssdp_search, self.own_ip()):
            try:
                res = await self.http.get(location, timeout=3)
            except httpx.HTTPError:
                continue
            root = _safe_xml(res.text)
            if root is None:
                continue
            for svc in root.iter():
                if not svc.tag.endswith("service"):
                    continue
                kids = {c.tag.split("}")[-1]: (c.text or "").strip() for c in svc}
                if kids.get("serviceType") == AVT and kids.get("controlURL"):
                    return urljoin(location, kids["controlURL"])
        return None

    async def track(self) -> dict[str, Any]:
        if self._control is None:
            self._control = await self._find()
            if self._control is None:
                return {}
        body = (
            '<?xml version="1.0"?><s:Envelope xmlns:s="http://schemas.xmlsoap.org/soap/envelope/"'
            ' s:encodingStyle="http://schemas.xmlsoap.org/soap/encoding/"><s:Body>'
            f'<u:GetPositionInfo xmlns:u="{AVT}"><InstanceID>0</InstanceID>'
            "</u:GetPositionInfo></s:Body></s:Envelope>"
        )
        try:
            res = await self.http.post(
                self._control,
                content=body,
                headers={
                    "Content-Type": 'text/xml; charset="utf-8"',
                    "SOAPACTION": f'"{AVT}#GetPositionInfo"',
                },
                timeout=3,
            )
        except httpx.HTTPError:
            self._control = None
            return {}
        if res.status_code != 200:
            self._control = None
            return {}
        m = re.search(r"<TrackMetaData>(.*?)</TrackMetaData>", res.text, re.S)
        info = parse_didl(unescape(m.group(1))) if m else {}
        art = info.get("image_url")
        if art and not urlparse(art).scheme:
            info["image_url"] = urljoin(self._control, art)
        return info
