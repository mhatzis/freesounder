"""go-librespot (Spotify Connect) config and local API client."""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

import httpx

logger = logging.getLogger(__name__)

UNIT = "freesounder-spotify.service"


def render_config(
    *,
    device_name: str,
    fifo: str,
    api_port: int = 3678,
    token_login: tuple[str, str] | None = None,
) -> str:
    """go-librespot config.yml (YAML is a superset of JSON for scalars).

    ``token_login`` = (username, access_token) logs in once with the app's
    Spotify token; go-librespot then stores reusable credentials in
    state.json and the normal (zeroconf) config picks them up again.
    """

    name = json.dumps(device_name)
    if token_login:
        username, token = token_login
        credentials = [
            "credentials:",
            "  type: spotify_token",
            "  spotify_token:",
            f"    username: {json.dumps(username)}",
            f"    access_token: {json.dumps(token)}",
        ]
    else:
        credentials = [
            "credentials:",
            "  type: zeroconf",
            "  zeroconf:",
            "    persist_credentials: true",
        ]
    return "\n".join(
        [
            "# Generated by freesounderd. Changes are overwritten.",
            f"device_name: {name}",
            "device_type: speaker",
            "audio_backend: pipe",
            f"audio_output_pipe: {json.dumps(fifo)}",
            "audio_output_pipe_format: s16le",
            "bitrate: 320",
            "volume_steps: 100",
            "initial_volume: 100",
            "external_volume: true",
            "zeroconf_enabled: true",
            "zeroconf_backend: avahi",
            *credentials,
            "metadata:",
            "  enabled: true",
            "server:",
            "  enabled: true",
            "  address: 127.0.0.1",
            f"  port: {api_port}",
            "  image_size: large",
            "",
        ]
    )


class LibrespotClient:
    def __init__(self, base: str, client: httpx.AsyncClient) -> None:
        self.base = base.rstrip("/")
        self._client = client

    async def status(self) -> dict[str, Any] | None:
        """Player status, or None when there is no session / daemon down."""

        try:
            res = await self._client.get(f"{self.base}/status", timeout=2)
        except httpx.HTTPError:
            return None
        if res.status_code != 200:
            return None
        try:
            return res.json()
        except ValueError:
            return None

    async def command(self, name: str, body: dict[str, Any] | None = None) -> bool:
        try:
            res = await self._client.post(f"{self.base}/player/{name}", json=body or {}, timeout=4)
        except httpx.HTTPError:
            return False
        return res.status_code < 300

    async def play(
        self, uri: str, *, skip_to_uri: str | None = None, position_ms: int | None = None
    ) -> tuple[bool, str]:
        body: dict[str, Any] = {"uri": uri}
        if skip_to_uri:
            body["skip_to_uri"] = skip_to_uri
        if position_ms:
            body["position"] = int(position_ms)
        try:
            res = await self._client.post(f"{self.base}/player/play", json=body, timeout=10)
        except httpx.HTTPError as exc:
            return False, f"Spotify player did not answer: {exc}"
        if res.status_code == 204:
            return False, "Spotify is not signed in on this player yet."
        if res.status_code >= 300:
            return False, f"Spotify player refused ({res.status_code}): {res.text[:200]}"
        return True, ""

    async def seek(self, position_ms: int) -> bool:
        return await self.command("seek", {"position": max(0, int(position_ms))})

    async def context_tracks(self, uri: str) -> dict[str, Any] | None:
        try:
            res = await self._client.get(
                f"{self.base}/context/tracks", params={"uri": uri}, timeout=10
            )
        except httpx.HTTPError:
            return None
        if res.status_code != 200:
            return None
        try:
            return res.json()
        except ValueError:
            return None

    async def set_device_name(self, name: str) -> bool:
        try:
            res = await self._client.post(
                f"{self.base}/set_device_name", json={"name": name}, timeout=4
            )
        except httpx.HTTPError:
            return False
        return res.status_code < 300


def is_playing(status: dict[str, Any] | None) -> bool:
    return bool(
        status and status.get("track") and not status.get("stopped") and not status.get("paused")
    )


def is_paused(status: dict[str, Any] | None) -> bool:
    return bool(
        status and status.get("track") and status.get("paused") and not status.get("stopped")
    )


def now_playing_fields(status: dict[str, Any]) -> dict[str, Any]:
    track = status.get("track") or {}
    position = track.get("position")
    duration = track.get("duration")
    return {
        "title": track.get("name"),
        "artist": ", ".join(track.get("artist_names") or []) or None,
        "album": track.get("album_name"),
        "image_url": track.get("album_cover_url"),
        "position": position / 1000 if isinstance(position, int | float) else None,
        "duration": duration / 1000 if isinstance(duration, int | float) else None,
        "uri": track.get("uri"),
        "context_uri": status.get("context_uri"),
        "context_name": status.get("context_name"),
    }


def read_state(spotify_dir: Path) -> dict[str, Any]:
    """go-librespot's state.json (device id, stored credentials)."""

    try:
        data = json.loads((spotify_dir / "state.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def clear_credentials(spotify_dir: Path) -> None:
    """Forget the stored Spotify login, keep the device id."""

    path = spotify_dir / "state.json"
    data = read_state(spotify_dir)
    if not data.get("credentials"):
        return
    data["credentials"] = {"username": "", "data": None}
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(data), encoding="utf-8")
    tmp.replace(path)


def stored_username(spotify_dir: Path) -> str | None:
    creds = read_state(spotify_dir).get("credentials") or {}
    return (creds.get("username") or None) if creds.get("data") else None
