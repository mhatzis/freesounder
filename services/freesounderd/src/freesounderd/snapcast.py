"""Minimal Snapcast JSON-RPC client (HTTP POST /jsonrpc) and config renderer."""

from __future__ import annotations

import itertools
import logging
from typing import Any

import httpx

logger = logging.getLogger(__name__)

STREAMS = ("Spotify", "AirPlay", "Radio", "Idle")
SOURCE_STREAM = {"spotify": "Spotify", "airplay": "AirPlay", "radio": "Radio", "none": "Idle"}
RELAY_GROUP_STREAM = "Idle"


class SnapcastError(RuntimeError):
    pass


class SnapcastRpc:
    def __init__(self, url: str, client: httpx.AsyncClient) -> None:
        self.url = url
        self._client = client
        self._ids = itertools.count(1)

    async def call(self, method: str, params: dict[str, Any] | None = None) -> Any:
        payload: dict[str, Any] = {"id": next(self._ids), "jsonrpc": "2.0", "method": method}
        if params is not None:
            payload["params"] = params
        try:
            res = await self._client.post(self.url, json=payload, timeout=4)
            data = res.json()
        except (httpx.HTTPError, ValueError) as exc:
            raise SnapcastError(f"{method}: {exc}") from exc
        if "error" in data:
            raise SnapcastError(f"{method}: {data['error']}")
        return data.get("result")

    async def status(self) -> dict[str, Any]:
        result = await self.call("Server.GetStatus")
        return (result or {}).get("server", {})

    async def set_client_volume(self, client_id: str, percent: int, muted: bool) -> None:
        await self.call(
            "Client.SetVolume",
            {"id": client_id, "volume": {"muted": muted, "percent": int(percent)}},
        )

    async def set_group_stream(self, group_id: str, stream_id: str) -> None:
        await self.call("Group.SetStream", {"id": group_id, "stream_id": stream_id})

    async def set_group_clients(self, group_id: str, clients: list[str]) -> None:
        await self.call("Group.SetClients", {"id": group_id, "clients": clients})

    async def set_group_mute(self, group_id: str, muted: bool) -> None:
        await self.call("Group.SetMute", {"id": group_id, "mute": muted})

    async def stream_control(self, stream_id: str, command: str) -> None:
        await self.call("Stream.Control", {"id": stream_id, "command": command})

    async def delete_client(self, client_id: str) -> None:
        await self.call("Server.DeleteClient", {"id": client_id})


def clients_of(server: dict[str, Any]) -> list[tuple[str, dict[str, Any]]]:
    """(group id, client) pairs from Server.GetStatus."""

    out: list[tuple[str, dict[str, Any]]] = []
    for group in server.get("groups", []):
        for client in group.get("clients", []):
            out.append((group.get("id", ""), client))
    return out


def stream_status(server: dict[str, Any], stream_id: str) -> dict[str, Any] | None:
    for stream in server.get("streams", []):
        if stream.get("id") == stream_id:
            return stream
    return None


def render_snapserver_conf(
    *,
    run_dir: str,
    airplay_name: str,
    shairport_bin: str,
    airplay_version: int,
) -> str:
    """snapserver.conf for a group leader. mDNS off: players find each other
    via _freesounder._tcp and members are pointed at the leader directly."""

    def esc(value: str) -> str:
        from urllib.parse import quote

        return quote(value, safe="")

    lines = [
        "# Generated by freesounderd. Changes are overwritten.",
        "[server]",
        "mdns_enabled = false",
        "",
        "[http]",
        "enabled = true",
        "bind_to_address = 0.0.0.0",
        "port = 1780",
        "publish_http = false",
        "",
        "[tcp-control]",
        "enabled = true",
        "bind_to_address = 0.0.0.0",
        "port = 1705",
        "publish = false",
        "",
        "[tcp-streaming]",
        "enabled = true",
        "bind_to_address = 0.0.0.0",
        "port = 1704",
        "publish = false",
        "",
        "[stream]",
        "sampleformat = 44100:16:2",
        "codec = flac",
        "buffer = 1000",
        "chunk_ms = 26",
        f"source = pipe://{run_dir}/spotify.fifo?name=Spotify&mode=read",
    ]
    if airplay_version:
        port = 7000 if airplay_version >= 2 else 5000
        lines.append(
            f"source = airplay://{shairport_bin}?name=AirPlay&devicename={esc(airplay_name)}"
            f"&port={port}"
        )
    lines += [
        f"source = pipe://{run_dir}/radio.fifo?name=Radio&mode=read",
        f"source = pipe://{run_dir}/idle.fifo?name=Idle&mode=read",
        "",
        "[logging]",
        "filter = *:info",
        "",
    ]
    return "\n".join(lines)
